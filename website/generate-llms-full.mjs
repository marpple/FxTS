// Generates docs/public/llms-full.txt - the llms.txt convention's expanded
// variant: the entire English documentation in one file so agents and LLMs
// can ingest it without crawling. Run after the API docs are generated
// (make all) and before `vitepress build`.
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const DOCS = new URL("./docs", import.meta.url).pathname;

const stripFrontmatter = (text) =>
  text
    .replace(/^---\n[\s\S]*?\n---\n/, "")
    .replace(
      /<!-- Do not edit this file\. It is generated automatically -->\n?/g,
      "",
    )
    .trim();

const readSection = async (dir, title) => {
  const files = (await readdir(join(DOCS, dir)))
    .filter((f) => f.endsWith(".md"))
    .sort();
  const pages = [];
  for (const file of files) {
    const body = stripFrontmatter(
      await readFile(join(DOCS, dir, file), "utf8"),
    );
    pages.push(body);
  }
  return `# ${title}\n\n${pages.join("\n\n---\n\n")}`;
};

const header = (await readFile(join(DOCS, "public/llms.txt"), "utf8")).trim();
const guide = await readSection("guide", "Guide");
const api = await readSection("api", "API Reference");

await writeFile(
  join(DOCS, "public/llms-full.txt"),
  [header, guide, api].join("\n\n---\n\n") + "\n",
);
console.log("generated docs/public/llms-full.txt");
